const NORMALIZED_EMOJI_MAP: Record<string, AppIconId> = Object.fromEntries(
  Object.entries(EMOJI_TO_ICON).map(([k, v]) => [k.replace(/\uFE0F/g, ""), v])
);

export function resolveIconId(value?: string | null, fallback: AppIconId = "tag"): AppIconId {
  if (!value || typeof value !== "string") return fallback;
  const trimmed = value.trim();
  if (!trimmed) return fallback;
  if (isAppIconId(trimmed)) return trimmed;
  if (trimmed in EMOJI_TO_ICON) return EMOJI_TO_ICON[trimmed];
  const normalized = trimmed.replace(/\uFE0F/g, "");
  if (normalized in NORMALIZED_EMOJI_MAP) return NORMALIZED_EMOJI_MAP[normalized];
  return fallback;
}
